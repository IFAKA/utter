"""Export the real v1 kit (housing meshes, PCB footprints, board render) to docs/assets/kit.js for the
landing page's 3D "what's in the box" viewer. Everything is in millimetres in pod.py's frame
(x along the board, y = 46 - KiCad y, z up). Run after pod.py changes:  python3 hardware/enclosure/web.py
"""
import base64
import json
import subprocess
import tempfile
from pathlib import Path

import numpy as np

import pod

DOCS = pod.HERE.parents[1] / "docs"


def mesh(m):
    me = m.to_mesh()
    return {"p": np.round(np.asarray(me.vert_properties)[:, :3], 2).ravel().tolist(),
            "i": np.asarray(me.tri_verts).ravel().tolist()}


def board_jpeg():
    with tempfile.TemporaryDirectory() as d:
        out = Path(d) / "b.jpg"
        subprocess.run(["sips", "-s", "format", "jpeg", "-s", "formatOptions", "82",
                        str(DOCS / "assets" / "board.png"), "--out", str(out)], check=True, capture_output=True)
        return "data:image/jpeg;base64," + base64.b64encode(out.read_bytes()).decode()


if __name__ == "__main__":
    kit = {
        "base": mesh(pod.build_base()), "lid": mesh(pod.build_lid()),
        "dims": {k: getattr(pod, k) for k in ("BW", "BH", "BT", "CL", "WALL", "FLOOR", "LID", "ZB", "ZT", "TOP", "STRAP")},
        "batt": pod.BATT, "bosses": pod.BOSSES,
        "parts": [[ref, *map(lambda v: round(v, 2), bb), h] for ref, bb, h in pod.parts()],
        "board": board_jpeg(),
    }
    js = "// generated by hardware/enclosure/web.py from pod.py and the KiCad board; do not edit\nwindow.KIT = " + json.dumps(kit, separators=(",", ":")) + ";\n"
    (DOCS / "assets" / "kit.js").write_text(js)
    print(f"kit.js: {len(js) // 1024} KB, {len(kit['parts'])} footprints")
